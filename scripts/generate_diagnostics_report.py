"""
generate_diagnostics_report.py
Diagnostic tables for the TF-IDF setting (replaces generate_mentor_report.py).

Everything is computed on the SAME rows the probes were scored on:
  * labels  = the `y` stored in probes/test_predictions.jsonl (pipeline labels, generated hops only)
  * texts / entities / retrieval condition = the local labeled.jsonl (matched by id)
  * hedges  = src.pipeline.common.is_hedge (one keyword list for the whole project)
  * probes  = the deployed ones (layer from probes_meta.json, calibrated P(fail), deployed tau)

Writes outputs/pipeline/tfidf/diagnostics.md and diagnostics.json.

    python scripts/generate_diagnostics_report.py
"""

import json
import math
import sys
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.stdout.reconfigure(encoding="utf-8")

from src.pipeline.common import is_hedge                      # noqa: E402

PROBE_DIR = ROOT / "outputs/pipeline/tfidf/probes"
LABELED = ROOT / "data_hf_cache/tfidf_distractor_rag/data/raw/2wikimultihopqa/labeled.jsonl"
OUT = ROOT / "outputs/pipeline/tfidf"
CONDS = ["both_present", "only_hop1_passage", "only_hop2_passage", "neither"]


def auroc(y, s):
    from sklearn.metrics import roc_auc_score
    y = np.asarray(y)
    return float(roc_auc_score(y, s)) if len(set(y.tolist())) > 1 else float("nan")


def recall_at_fpr(y, s, target):
    from sklearn.metrics import roc_curve
    fpr, tpr, _ = roc_curve(y, s)
    return float(tpr[fpr <= target].max())


def wilson(k, n, z=1.96):
    if n == 0:
        return (float("nan"),) * 2
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def hop_titles(r):
    """(hop1_title, hop2_title, method) — same rule as scripts/fix_retrieval_conditions.py."""
    g = r.get("gold_titles", [])
    q = r.get("question", "").lower()
    if len(g) < 2:
        return None, None, "missing"
    in_q = [(t.split(" (")[0].lower() in q) or (t.lower() in q) for t in g[:2]]
    if in_q[0] and not in_q[1]:
        return g[0], g[1], "question"
    if in_q[1] and not in_q[0]:
        return g[1], g[0], "question"
    be = next((n.get("gold_entity", "").lower() for n in r.get("reasoning_graph", []) if n.get("hop") == 1), "")
    if be and (be in g[1].lower() or g[1].lower() in be):
        return g[0], g[1], "bridge_entity"
    if be and (be in g[0].lower() or g[0].lower() in be):
        return g[1], g[0], "bridge_entity"
    return g[0], g[1], "FALLBACK_alphabetical"


def flat_context(r):
    c = r.get("context", "")
    if isinstance(c, str):
        return c.lower()
    return " ".join(f"{p[0]} {' '.join(p[1])}" if isinstance(p, (list, tuple)) and len(p) > 1 else str(p)
                    for p in c).lower()


def main():
    meta = json.loads((PROBE_DIR / "probes_meta.json").read_text())
    test_ids, train_ids = set(meta["test_ids"]), set(meta["train_ids"])
    tau = {t: meta["probes"][t]["tau"] for t in meta["probes"]}
    layer = {t: meta["probes"][t]["layer"] for t in meta["probes"]}
    recs = {}
    with open(LABELED, encoding="utf-8") as f:
        for l in f:
            d = json.loads(l)
            recs[d["id"]] = d
    preds = defaultdict(dict)
    for l in open(PROBE_DIR / "test_predictions.jsonl", encoding="utf-8"):
        d = json.loads(l)
        preds[d["task"]][(d["id"], d["hop"])] = d

    R, md = {}, []
    P = md.append

    # ── 1. retrieval conditions ──────────────────────────────────────────────
    methods = Counter(hop_titles(r)[2] for r in recs.values())
    cond_all = Counter(r["retrieval_condition"] for r in recs.values())
    cond_test = Counter(recs[i]["retrieval_condition"] for i in test_ids if i in recs)
    R["condition_all"], R["condition_test"], R["hop_order_method"] = dict(cond_all), dict(cond_test), dict(methods)
    P("# Diagnostics (TF-IDF setting)\n\nGenerated by `scripts/generate_diagnostics_report.py`. Labels = pipeline labels "
      "(`test_predictions.jsonl`); probes = deployed (layer 10, calibrated P(fail), deployed τ).\n")
    P("## 1. Retrieval conditions (true hop order)\n")
    P("| condition | all (N=4000) | test (N=800) |\n|---|---|---|")
    for c in CONDS:
        P(f"| {c} | {cond_all[c]} ({cond_all[c] / sum(cond_all.values()):.1%}) | "
          f"{cond_test[c]} ({cond_test[c] / sum(cond_test.values()):.1%}) |")
    P(f"\nHop order resolved by: {dict(methods)}. **`FALLBACK_alphabetical` rows are the ones that could still carry the "
      f"old p1/p2 mix-up.**\n")

    # ── 2. failure rates and cascading (generated hops only) ─────────────────
    y1 = {i: p["y"] for (i, h), p in preds["hop1"].items()}
    y2 = {i: p["y"] for (i, h), p in preds["hop2"].items()}
    both = [i for i in y1 if i in y2]
    casc = sum(1 for i in both if y1[i] and y2[i])
    h2f = sum(y2[i] for i in both)
    h1s = [i for i in both if not y1[i]]
    R["rates"] = dict(hop1=(sum(y1.values()), len(y1)), hop2=(sum(y2.values()), len(y2)), both_generated=len(both),
                      cascading=casc, hop2_fail_among_both=h2f, hop2_fail_given_hop1_ok=(sum(y2[i] for i in h1s), len(h1s)))
    P("## 2. Failure rates (generated hops only, test split)\n")
    P(f"* Hop 1: {sum(y1.values())}/{len(y1)} = {sum(y1.values()) / len(y1):.1%}")
    P(f"* Hop 2: {sum(y2.values())}/{len(y2)} = {sum(y2.values()) / len(y2):.1%} "
      f"({800 - len(y2)} test questions never closed hop 2 and are excluded)")
    P(f"* Questions with both hops generated: {len(both)}; hop-2 failures among them: {h2f}")
    P(f"* Cascading (hop 1 failed and hop 2 failed): {casc}/{h2f} = {casc / h2f:.1%} of those hop-2 failures")
    P(f"* Hop-2 failure rate given hop 1 succeeded: {sum(y2[i] for i in h1s)}/{len(h1s)} = "
      f"{sum(y2[i] for i in h1s) / len(h1s):.1%}\n")
    P("Hop-2 failure rate when hop 1 succeeded, by retrieval condition:\n")
    P("| condition | n | hop-2 fails | rate |\n|---|---|---|---|")
    R["hop2_by_cond"] = {}
    for c in CONDS:
        ids = [i for i in h1s if recs[i]["retrieval_condition"] == c]
        k = sum(y2[i] for i in ids)
        R["hop2_by_cond"][c] = (k, len(ids))
        P(f"| {c} | {len(ids)} | {k} | {k / len(ids):.1%} |" if ids else f"| {c} | 0 | – | – |")
    P("")

    # ── 3. probe detection ───────────────────────────────────────────────────
    P("## 3. Deployed probes on the test split (layer 10)\n")
    P("`conf.` = hedges removed (confident failures vs successes). Recall @ τ uses the deployed calibrated threshold.\n")
    P("| probe | rows | fails | τ | AUROC all | AUROC conf. | conf. fails | recall@5%FPR | recall@10%FPR | recall@τ (conf.) |"
      "\n|---|---|---|---|---|---|---|---|---|---|")
    R["probes"] = {}
    for task in ("hop1", "hop2", "hop12"):
        rows = list(preds[task].values())
        y = np.array([r["y"] for r in rows])
        s = np.array([r["p_fail"] for r in rows])
        txt = {}
        for (i, h) in preds[task]:
            hh = next((x for x in recs[i]["hops"] if x["hop_idx"] == h), {})
            txt[(i, h)] = hh.get("text", "")
        hedge = np.array([is_hedge(txt[(r["id"], r["hop"])]) for r in rows])
        keep = ~(hedge & (y == 1))
        yc, sc = y[keep], s[keep]
        R["probes"][task] = dict(n=len(y), n_fail=int(y.sum()), tau=tau[task], auroc=auroc(y, s), auroc_conf=auroc(yc, sc),
                                 n_conf_fail=int(yc.sum()), r5=recall_at_fpr(yc, sc, .05), r10=recall_at_fpr(yc, sc, .10),
                                 recall_tau_conf=float((sc[yc == 1] >= tau[task]).mean()))
        q = R["probes"][task]
        P(f"| {task} (L{layer[task]}) | {q['n']} | {q['n_fail']} | {q['tau']:.3f} | {q['auroc']:.3f} | {q['auroc_conf']:.3f} | "
          f"{q['n_conf_fail']} | {q['r5']:.1%} | {q['r10']:.1%} | {q['recall_tau_conf']:.1%} |")
    P("")

    # ── 4. AUROC within each retrieval condition (shared probe) ──────────────
    P("## 4. Shared-probe AUROC within each retrieval condition (test split)\n")
    P("| condition | hop | n | fails | AUROC |\n|---|---|---|---|---|")
    R["auroc_by_cond"] = {}
    for c in CONDS:
        for hop in (1, 2):
            rows = [p for (i, h), p in preds["hop12"].items() if h == hop and recs[i]["retrieval_condition"] == c]
            y = [r["y"] for r in rows]
            a = auroc(y, [r["p_fail"] for r in rows]) if len(set(y)) > 1 else float("nan")
            R["auroc_by_cond"][f"{c}/hop{hop}"] = dict(n=len(rows), fails=int(sum(y)), auroc=a)
            note = "" if len(set(y)) > 1 else " (one class only)"
            P(f"| {c} | {hop} | {len(rows)} | {int(sum(y))} | {a:.3f}{note} |")
    P("")

    # ── 5. hop-1 confident failure dissection ────────────────────────────────
    cats = defaultdict(list)
    for (i, h), p in preds["hop1"].items():
        if p["y"] != 1:
            continue
        hh = next((x for x in recs[i]["hops"] if x["hop_idx"] == 1), {})
        if is_hedge(hh.get("text", "")):
            continue
        pe = (hh.get("bridging_entity_pred") or "").strip().lower()
        if pe and pe in recs[i]["question"].lower():
            cat = "restated_question"
        elif pe and pe in flat_context(recs[i]):
            cat = "distractor_copy"
        else:
            cat = "pure_fabrication"
        cats[cat].append(p["p_fail"])
    tot = sum(len(v) for v in cats.values())
    P(f"## 5. Hop-1 confident failures (N={tot}) — dedicated hop-1 probe, τ={tau['hop1']:.3f}\n")
    P("| category | n | share | flagged at τ | recall | 95% Wilson CI |\n|---|---|---|---|---|---|")
    R["hop1_dissection"] = {}
    for cat in ("restated_question", "distractor_copy", "pure_fabrication"):
        v = cats[cat]
        k = sum(1 for x in v if x >= tau["hop1"])
        lo, hi = wilson(k, len(v))
        R["hop1_dissection"][cat] = dict(n=len(v), flagged=k)
        P(f"| {cat} | {len(v)} | {len(v) / tot:.1%} | {k} | {k / len(v):.1%} | [{lo:.1%}, {hi:.1%}] |")
    P("\n`restated_question` = the extracted entity already appears in the question (the step dodged the question).\n")

    # ── 6. baselines on the same rows ────────────────────────────────────────
    from sklearn.feature_extraction.text import TfidfVectorizer
    from sklearn.linear_model import LogisticRegression

    def rows_for(ids, task_hops=(1, 2)):
        out = []
        for i in ids:
            r = recs.get(i)
            if r is None:
                continue
            order = [s["hop_idx"] for s in r.get("hop_spans", [])]
            for h in r["hops"]:
                if h["hop_idx"] in task_hops and h.get("label") in (0, 1) and h["hop_idx"] in order:
                    out.append((i, h["hop_idx"], int(h["label"]), h.get("text", "")))
        return out

    tr, te = rows_for(train_ids), rows_for(test_ids)
    vec = TfidfVectorizer(ngram_range=(1, 2), min_df=2)
    Xtr, Xte = vec.fit_transform([t[3] for t in tr]), vec.transform([t[3] for t in te])
    lr = LogisticRegression(max_iter=1000, class_weight="balanced").fit(Xtr, [t[2] for t in tr])
    yt = np.array([t[2] for t in te])
    P("## 6. Baselines on hops 1–2 of the test split\n")
    P("| baseline | AUROC | accuracy |\n|---|---|---|")
    maj = max(yt.mean(), 1 - yt.mean())
    hopidx = np.array([t[1] for t in te])
    R["baselines"] = dict(n=len(yt), majority_acc=float(maj), hop_index_auroc=auroc(yt, hopidx),
                          tfidf_text_auroc=auroc(yt, lr.predict_proba(Xte)[:, 1]),
                          shared_probe_auroc=R["probes"]["hop12"]["auroc"])
    P(f"| majority class | 0.500 | {maj:.3f} |")
    P(f"| hop index only | {R['baselines']['hop_index_auroc']:.3f} | – |")
    P(f"| TF-IDF on hop text | {R['baselines']['tfidf_text_auroc']:.3f} | – |")
    P(f"| shared probe (L10) | {R['baselines']['shared_probe_auroc']:.3f} | – |\n")

    # ── 7. per-layer CV AUROC (train split, from probes_meta) ────────────────
    P("## 7. Train-split grouped 5-fold CV AUROC by layer (block output L)\n")
    P("| layer | hop1 | hop2 | hop12 |\n|---|---|---|---|")
    for L in range(28):
        P(f"| {L} | " + " | ".join(f"{meta['cv_auroc'][t][str(L)]:.3f}" for t in ('hop1', 'hop2', 'hop12')) + " |")
    P("")

    (OUT / "diagnostics.md").write_text("\n".join(md), encoding="utf-8")
    (OUT / "diagnostics.json").write_text(json.dumps(R, indent=1), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
