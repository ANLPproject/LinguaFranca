    "import numpy as np\n",
    "import torch\n",
    "\n",
    "def extract_data(ex_list, hs_dir, layer_idx, hop_filter=None):\n",
    "    \"\"\"\n",
    "    Extract hidden states, labels, and metadata.\n",
    "    hop_filter: None (all hops), 0 (hop-1 only), 1 (hop-2 only)\n",
    "    Returns: X, y, hop_idxs, texts, gold_entities, retrieval_conditions, example_ids\n",
    "    \"\"\"\n",
    "    X, y, hop_idxs, texts, gold_ents, ret_conds, ex_ids = [], [], [], [], [], [], []\n",
    "    for ex in ex_list:\n",
    "        pt_path = hs_dir / f\"{ex['id']}.pt\"\n",
    "        if not pt_path.exists():\n",
    "            continue\n",
    "        data = torch.load(pt_path, weights_only=False)\n",
    "        pooled = data['pooled']  # [n_layers, n_hops, hidden_dim]\n",
    "        for hop in ex.get('hops', []):\n",
    "            h_idx = hop['hop_idx'] - 1  # hop 1 -> index 0\n",
    "            if hop.get('label') not in (0, 1):\n",
    "                continue\n",
    "            if hop_filter is not None and h_idx != hop_filter:\n",
    "                continue\n",
    "            if h_idx >= pooled.shape[1]:\n",
    "                continue\n",
    "            vec = pooled[layer_idx, h_idx].detach().numpy()\n",
    "            X.append(np.nan_to_num(vec))\n",
    "            y.append(hop['label'])\n",
    "            hop_idxs.append(h_idx)\n",
    "            texts.append(hop.get('text', ''))\n",
    "            gold_ents.append(hop.get('bridging_entity_gold', ''))\n",
    "            ret_conds.append(ex.get('retrieval_condition', 'unknown'))\n",
    "            ex_ids.append(ex['id'])\n",
    "    return (\n",
    "        np.array(X) if X else np.zeros((0, pooled.shape[2])),\n",
    "        np.array(y),\n",
    "        np.array(hop_idxs),\n",
    "        texts, gold_ents, ret_conds, ex_ids\n",
    "    )\n",
    "\n",
    "print('Feature extraction helpers ready.')\n"
